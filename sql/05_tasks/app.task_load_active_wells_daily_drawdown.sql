create or replace task CYGNET_TRANSFORMATION.APP.TASK_LOAD_ACTIVE_WELLS_DAILY_DRAWDOWN
	warehouse=REPORTING_WH
	schedule='USING CRON 0 6 * * * America/Chicago'
	SUSPEND_TASK_AFTER_NUM_FAILURES=3
	USER_TASK_TIMEOUT_MS=3600000
	TIMEZONE='America/Chicago'
	COMMENT='Daily 06:00 Central: recalculates DAILY_EST_DRAWDOWN for all active wells for the previous Central day via set-based SP_LOAD_ACTIVE_WELLS_DAILY_DRAWDOWN_SET. Idempotent.'
	as EXECUTE IMMEDIATE
$$
DECLARE
    v_result VARCHAR;
BEGIN
    CALL CYGNET_TRANSFORMATION.APP.SP_LOAD_ACTIVE_WELLS_DAILY_DRAWDOWN_SET(CURRENT_DATE - 1, CURRENT_DATE - 1) INTO :v_result;
    CALL SYSTEM$SET_RETURN_VALUE(:v_result);
END;
$$;
